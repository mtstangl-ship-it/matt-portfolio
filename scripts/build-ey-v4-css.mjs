/**
 * Merge Case EY V4 handoff CSS and prefix every rule with
 * `.tier-a-case-root .case-ey-portfolio` for soft-nav safety.
 * Skips @keyframes blocks (contents unchanged).
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = path.dirname(new URL(import.meta.url).pathname);
const PKG = path.dirname(ROOT);
const HANDOFF = path.join(PKG, ".v4-extract/case-ey/v4-handoff/styles");
const OUT = path.join(PKG, "src/styles/case-ey/ey-case.css");

const SCOPE = ".tier-a-case-root .case-ey-portfolio";

function stripCommentsOutsideStrings(s) {
  let out = "";
  let i = 0;
  while (i < s.length) {
    if (s[i] === "/" && s[i + 1] === "*") {
      const end = s.indexOf("*/", i + 2);
      if (end === -1) break;
      out += " ";
      i = end + 2;
      continue;
    }
    out += s[i];
    i++;
  }
  return out;
}

function findMatchingBrace(css, openIdx) {
  let depth = 0;
  for (let i = openIdx; i < css.length; i++) {
    if (css[i] === "{") depth++;
    else if (css[i] === "}") {
      depth--;
      if (depth === 0) return i;
    }
  }
  return -1;
}

function prefixSelectorList(sel) {
  return sel
    .split(",")
    .map((part) => {
      const s = part.trim();
      if (!s) return s;
      if (s.startsWith("@")) return s;
      if (s.startsWith(".tier-a-case-root")) return s;
      if (s.startsWith(".case-ey-portfolio")) return `.tier-a-case-root ${s}`;
      return `${SCOPE} ${s}`;
    })
    .join(", ");
}

function processBlock(css) {
  let i = 0;
  let out = "";
  while (i < css.length) {
    while (/\s/.test(css[i] || "")) out += css[i++];
    if (i >= css.length) break;

    if (css[i] === "@") {
      const semi = css.indexOf(";", i);
      const brace = css.indexOf("{", i);
      if (brace !== -1 && (semi === -1 || brace < semi)) {
        const preludeEnd = brace;
        const prelude = css.slice(i, preludeEnd).trim();
        const innerOpen = brace;
        const innerClose = findMatchingBrace(css, innerOpen);
        if (innerClose === -1) throw new Error("Unbalanced braces at @" + i);
        const inner = css.slice(innerOpen + 1, innerClose);
        const lower = prelude.toLowerCase();
        if (lower.startsWith("@keyframes") || lower.startsWith("@font-face")) {
          out += prelude + "{" + inner + "}";
        } else {
          out += prelude + "{" + processBlock(inner) + "}";
        }
        i = innerClose + 1;
        continue;
      }
      const end = semi === -1 ? css.length : semi + 1;
      out += css.slice(i, end);
      i = end;
      continue;
    }

    const open = css.indexOf("{", i);
    if (open === -1) {
      out += css.slice(i);
      break;
    }
    const selectors = css.slice(i, open).trim();
    const close = findMatchingBrace(css, open);
    if (close === -1) throw new Error("Unbalanced braces");
    const inner = css.slice(open + 1, close);
    out += prefixSelectorList(selectors) + "{" + processBlock(inner) + "}";
    i = close + 1;
  }
  return out;
}

function stripNavBlock(src) {
  const start = src.indexOf("/* ====================== NAV ====================== */");
  const picker = src.indexOf("/* ====================== CASE PICKER", start + 1);
  if (start === -1 || picker === -1) return src;
  return src.slice(0, start) + src.slice(picker);
}

const a = fs.readFileSync(path.join(HANDOFF, "case-ey.css"), "utf8");
const b = fs.readFileSync(path.join(HANDOFF, "case-ey-v3.css"), "utf8");
const c = fs.readFileSync(path.join(HANDOFF, "case-ey-v4.css"), "utf8");

let merged = stripNavBlock(a) + "\n" + b + "\n" + c;
merged = stripCommentsOutsideStrings(merged);
const prefixed = processBlock(merged);

const banner = `/* AUTO-GENERATED by scripts/build-ey-v4-css.mjs — do not edit by hand.
 * Source: .v4-extract/case-ey/v4-handoff/styles/case-ey*.css (nav block stripped).
 * Every selector prefixed with ${SCOPE}
 */

`;

fs.writeFileSync(OUT, banner + prefixed + "\n");
console.log("Wrote", OUT, `(≈${Math.round(prefixed.length / 1024)}kb)`);
